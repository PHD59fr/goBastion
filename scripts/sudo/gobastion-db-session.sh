#!/bin/sh
set -eu
[ "$(id -u)" = 0 ] && [ -n "${SUDO_USER:-}" ] && [ "${SUDO_USER}" != root ] || exit 2
DB_DRIVER_VALUE= DB_DSN_VALUE= EGRESS_ENC_KEY_VALUE= EGRESS_ENC_KEY_ID_VALUE=default EGRESS_ENC_KEYS_VALUE='{}' INSTANCE_ID_VALUE= OBS_ENABLED_VALUE=false
OTEL_SDK_DISABLED_VALUE=""
OTEL_TRACES_EXPORTER_VALUE=""
OTEL_EXPORTER_OTLP_ENDPOINT_VALUE=""
OTEL_EXPORTER_OTLP_TRACES_ENDPOINT_VALUE=""
OTEL_EXPORTER_OTLP_ALLOW_HTTP_LOOPBACK_VALUE=""
OTEL_SERVICE_NAME_VALUE=""
while IFS= read -r line || [ -n "$line" ]; do
 key=${line%%=*};value=${line#*=}
 case "$key" in
 DB_DRIVER) DB_DRIVER_VALUE=$value;; DB_DSN) DB_DSN_VALUE=$value;;
 EGRESS_ENC_KEY) EGRESS_ENC_KEY_VALUE=$value;;
 EGRESS_ENC_KEY_ID) EGRESS_ENC_KEY_ID_VALUE=$value;;
 EGRESS_ENC_KEYS) EGRESS_ENC_KEYS_VALUE=$value;; INSTANCE_ID) INSTANCE_ID_VALUE=$value;;
 OBS_ENABLED) OBS_ENABLED_VALUE=$value;;
 OTEL_SDK_DISABLED) OTEL_SDK_DISABLED_VALUE=$value;;
 OTEL_TRACES_EXPORTER) OTEL_TRACES_EXPORTER_VALUE=$value;;
 OTEL_EXPORTER_OTLP_ENDPOINT) OTEL_EXPORTER_OTLP_ENDPOINT_VALUE=$value;;
 OTEL_EXPORTER_OTLP_TRACES_ENDPOINT) OTEL_EXPORTER_OTLP_TRACES_ENDPOINT_VALUE=$value;;
 OTEL_EXPORTER_OTLP_ALLOW_HTTP_LOOPBACK) OTEL_EXPORTER_OTLP_ALLOW_HTTP_LOOPBACK_VALUE=$value;;
 OTEL_SERVICE_NAME) OTEL_SERVICE_NAME_VALUE=$value;;
 esac
done < /run/gobastion/db.conf
exec /usr/bin/env "DB_DRIVER=$DB_DRIVER_VALUE" "DB_DSN=$DB_DSN_VALUE" "EGRESS_ENC_KEY=$EGRESS_ENC_KEY_VALUE" "EGRESS_ENC_KEY_ID=$EGRESS_ENC_KEY_ID_VALUE" "EGRESS_ENC_KEYS=$EGRESS_ENC_KEYS_VALUE" "INSTANCE_ID=$INSTANCE_ID_VALUE" "OBS_ENABLED=$OBS_ENABLED_VALUE" "OTEL_SDK_DISABLED=$OTEL_SDK_DISABLED_VALUE" "OTEL_TRACES_EXPORTER=$OTEL_TRACES_EXPORTER_VALUE" "OTEL_EXPORTER_OTLP_ENDPOINT=$OTEL_EXPORTER_OTLP_ENDPOINT_VALUE" "OTEL_EXPORTER_OTLP_TRACES_ENDPOINT=$OTEL_EXPORTER_OTLP_TRACES_ENDPOINT_VALUE" "OTEL_EXPORTER_OTLP_ALLOW_HTTP_LOOPBACK=$OTEL_EXPORTER_OTLP_ALLOW_HTTP_LOOPBACK_VALUE" "OTEL_SERVICE_NAME=$OTEL_SERVICE_NAME_VALUE" /app/goBastion --dbSession "$@"
